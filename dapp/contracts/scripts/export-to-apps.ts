// Copies ABI + address + deployment block into backend/ and frontend/ after every deploy.
//   npm run export                  -> Sepolia deployment (chain 11155111)
//   CHAIN_ID=31337 npm run export   -> another chain's Ignition deployment
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { CONTRACT_NAME, IGNITION_MODULE } from "./dapp.config.js";

const CONTRACT = CONTRACT_NAME;
const MODULE_KEY = `${IGNITION_MODULE}#${CONTRACT}`;
const chainId = Number(process.env.CHAIN_ID ?? 11155111);

const root = path.resolve(import.meta.dirname, "..");
const artifactPath = path.join(root, `artifacts/contracts/${CONTRACT}.sol/${CONTRACT}.json`);
if (!existsSync(artifactPath)) throw new Error("No artifact - run `npm run build -w contracts` first.");
const { abi } = JSON.parse(readFileSync(artifactPath, "utf8"));

const deployDir = path.join(root, `ignition/deployments/chain-${chainId}`);
if (!existsSync(deployDir)) throw new Error(`No Ignition deployment for chain ${chainId}. Deploy first.`);
const address: string = JSON.parse(readFileSync(path.join(deployDir, "deployed_addresses.json"), "utf8"))[MODULE_KEY];

// Deployment block from Ignition's journal -> where the backend starts indexing
let deployBlock = 0;
for (const line of readFileSync(path.join(deployDir, "journal.jsonl"), "utf8").split("\n")) {
  if (!line.includes(MODULE_KEY) || !line.includes("blockNumber")) continue;
  const n = JSON.parse(line)?.receipt?.blockNumber;
  if (typeof n === "number") deployBlock = n;
}

const file = `// AUTO-GENERATED by contracts/scripts/export-to-apps.ts - do not edit by hand.
export const CHAIN_ID = ${chainId};
export const CONTRACT_ADDRESS = "${address}" as const;
export const DEPLOY_BLOCK = ${deployBlock};
export const VOTING_ABI = ${JSON.stringify(abi, null, 2)} as const;
`;
for (const target of ["backend/src/generated/contract.ts", "frontend/src/generated/contract.ts"]) {
  const out = path.resolve(root, "..", target);
  mkdirSync(path.dirname(out), { recursive: true });
  writeFileSync(out, file);
  console.log(`✔ wrote ${target}  (${CONTRACT} @ ${address}, chain ${chainId}, deploy block ${deployBlock})`);
}
